package app.linear.platform.u202216448.planning.interfaces.rest;

import app.linear.platform.u202216448.planning.application.commandservices.RoadmapCycleCommandService;
import app.linear.platform.u202216448.planning.application.queryservices.RoadmapCycleQueryService;
import app.linear.platform.u202216448.planning.domain.model.aggregates.RoadmapCycle;
import app.linear.platform.u202216448.planning.domain.model.queries.GetRoadmapCycleByIdQuery;
import app.linear.platform.u202216448.planning.interfaces.rest.resources.CreateRoadmapCycleResource;
import app.linear.platform.u202216448.planning.interfaces.rest.resources.RoadmapCycleResource;
import app.linear.platform.u202216448.planning.interfaces.rest.transform.CreateRoadmapCycleCommandFromResourceAssembler;
import app.linear.platform.u202216448.planning.interfaces.rest.transform.RoadmapCycleResourceFromEntityAssembler;
import app.linear.platform.u202216448.shared.application.result.ApplicationError;
import app.linear.platform.u202216448.shared.application.result.Result;
import app.linear.platform.u202216448.shared.interfaces.rest.transform.ResponseEntityAssembler;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.responses.ApiResponses;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import static org.springframework.http.MediaType.APPLICATION_JSON_VALUE;

/**
 * REST controller that exposes roadmap cycle resources.
 *
 * @author Gustavo Alonso Olivares Lao
 */
@RestController
@RequestMapping(value = "/api/v1/roadmap-cycles", produces = APPLICATION_JSON_VALUE)
@Tag(name = "Roadmap Cycles", description = "Roadmap cycle management endpoints")
public class RoadmapCyclesController {
    private final RoadmapCycleCommandService roadmapCycleCommandService;
    private final RoadmapCycleQueryService roadmapCycleQueryService;

    /**
     * Constructor
     *
     * @param roadmapCycleCommandService The {@link RoadmapCycleCommandService} instance
     * @param roadmapCycleQueryService   The {@link RoadmapCycleQueryService} instance
     */
    public RoadmapCyclesController(RoadmapCycleCommandService roadmapCycleCommandService, RoadmapCycleQueryService roadmapCycleQueryService) {
        this.roadmapCycleCommandService = roadmapCycleCommandService;
        this.roadmapCycleQueryService = roadmapCycleQueryService;
    }

    /**
     * Create a new roadmap cycle
     *
     * @param resource The {@link CreateRoadmapCycleResource} instance
     * @return The {@link RoadmapCycleResource} resource for the created roadmap cycle
     */
    @PostMapping
    @Operation(summary = "Create a new roadmap cycle", description = "Creates a new roadmap cycle. The id is generated by the system and the status is PLANNED when it is not specified.")
    @ApiResponses(value = {
            @ApiResponse(
                responseCode = "201",
                description = "Roadmap cycle created successfully",
                content = @Content(schema = @Schema(implementation = RoadmapCycleResource.class))
            ),
            @ApiResponse(responseCode = "400", description = "Invalid input data"),
            @ApiResponse(responseCode = "409", description = "Conflict - A roadmap cycle with the same cycle code already exists")
    })
    public ResponseEntity<?> createRoadmapCycle(@Valid @RequestBody CreateRoadmapCycleResource resource) {
        var createRoadmapCycleCommand = CreateRoadmapCycleCommandFromResourceAssembler.toCommandFromResource(resource);
        var result = roadmapCycleCommandService.handle(createRoadmapCycleCommand)
                .flatMap(id -> roadmapCycleQueryService.handle(new GetRoadmapCycleByIdQuery(id))
                        .<Result<RoadmapCycle, ApplicationError>>map(Result::success)
                        .orElseGet(() -> Result.failure(ApplicationError.notFound("RoadmapCycle", id.toString()))));

        return ResponseEntityAssembler.toResponseEntityFromResult(
                result,
                RoadmapCycleResourceFromEntityAssembler::toResourceFromEntity,
                HttpStatus.CREATED
        );
    }
}
